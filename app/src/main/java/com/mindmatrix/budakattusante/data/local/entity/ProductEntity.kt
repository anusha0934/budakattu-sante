package com.mindmatrix.budakattusante.data.local.entity

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.mindmatrix.budakattusante.data.model.Product

@Entity(tableName = "products")
data class ProductEntity(
    @PrimaryKey val productId: String,
    val vendorId: String,
    val artisanId: String,
    val batchId: String,
    val name: String,
    val category: String,
    val availableKg: Double,
    val pricePerKg: Double,
    val mspPrice: Double,
    val marketPrice: Double,
    val fairTradeMargin: Double,
    val governmentApproved: Boolean,
    val isFairTradeCertified: Boolean,
    val certificationId: String,
    val pricingAuthority: String,
    val mspLastUpdated: String,
    val tribalShare: Double,
    val familyName: String,
    val tribeName: String,
    val forestRegion: String,
    val village: String,
    val collectionZone: String,
    val location: String,
    val locationLat: Double,
    val locationLng: Double,
    val rating: Double,
    val sellerPhone: String,
    val description: String,
    val harvestDate: String,
    val expiryDate: String,
    val imageUrl: String,
    val vendorProfileImageUrl: String,
    val artisanImageUrl: String,
    val audioDescUrl: String,
    val isHandmade: Boolean,
    val isPreOrder: Boolean,
    val preorderStock: Int,
    val preorderCount: Int,
    val expectedHarvestDate: String,
    // Sync Metadata
    val lastUpdated: Long = System.currentTimeMillis(),
    val isDeleted: Boolean = false,
    val version: Int = 1
)

fun ProductEntity.toProduct() = Product(
    productId = productId,
    vendorId = vendorId,
    artisanId = artisanId,
    batchId = batchId,
    name = name,
    category = category,
    availableKg = availableKg,
    pricePerKg = pricePerKg,
    mspPrice = mspPrice,
    marketPrice = marketPrice,
    fairTradeMargin = fairTradeMargin,
    governmentApproved = governmentApproved,
    isFairTradeCertified = isFairTradeCertified,
    certificationId = certificationId,
    pricingAuthority = pricingAuthority,
    mspLastUpdated = mspLastUpdated,
    tribalShare = tribalShare,
    familyName = familyName,
    tribeName = tribeName,
    forestRegion = forestRegion,
    village = village,
    collectionZone = collectionZone,
    location = location,
    locationLat = locationLat,
    locationLng = locationLng,
    rating = rating,
    sellerPhone = sellerPhone,
    description = description,
    harvestDate = harvestDate,
    expiryDate = expiryDate,
    imageUrl = imageUrl,
    vendorProfileImageUrl = vendorProfileImageUrl,
    artisanImageUrl = artisanImageUrl,
    audioDescUrl = audioDescUrl,
    isHandmade = isHandmade,
    isPreOrder = isPreOrder,
    preorderStock = preorderStock,
    preorderCount = preorderCount,
    expectedHarvestDate = expectedHarvestDate,
    isLocalPendingSync = false // Will be determined by sync queue state in repo
)

